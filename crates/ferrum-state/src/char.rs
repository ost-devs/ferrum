/// The number of numbers of [`EXTENDERS`]: one more than its commas.
const fn count_numbers(s: &[u8]) -> usize {
    let (mut n, mut i) = (1, 0);
    while i < s.len() {
        if s[i] == b',' {
            n += 1;
        }
        i += 1;
    }
    n
}

const NUMBERS: usize = count_numbers(EXTENDERS.as_bytes());

/// The ranges of extending code points, `from` included and `to` excluded, decoded from [`EXTENDERS`] as the package
/// decodes it at load (`index.js:12-14`): each number is added to the running total, which is alternately a range's
/// start and its end. Decoded at compile time.
const RANGES: ([u32; NUMBERS / 2], [u32; NUMBERS / 2]) = {
    let s = EXTENDERS.as_bytes();
    let mut range_from = [0u32; NUMBERS / 2];
    let mut range_to = [0u32; NUMBERS / 2];
    let (mut i, mut k, mut n) = (0, 0, 0u32);
    while k < NUMBERS {
        let (mut value, mut digits) = (0u32, 0);
        while i < s.len() && s[i] != b',' {
            let d = s[i];
            let digit = if d.is_ascii_digit() { d - b'0' } else { d - b'a' + 10 };
            value = value * 36 + digit as u32;
            digits += 1;
            i += 1;
        }
        i += 1;
        n += if digits == 0 { 1 } else { value };
        if k % 2 == 1 {
            range_to[k / 2] = n;
        } else {
            range_from[k / 2] = n;
        }
        k += 1;
    }
    (range_from, range_to)
};

/// Whether a code point is in the extending table (`isExtendingChar`, `index.js:17`).
pub(crate) fn is_extending_char(code: u32) -> bool {
    if code < 768 {
        return false;
    }
    let (range_from, range_to) = (&RANGES.0, &RANGES.1);
    let (mut from, mut to) = (0, range_from.len());
    loop {
        let mid = (from + to) >> 1;
        if code < range_from[mid] {
            to = mid;
        } else if code >= range_to[mid] {
            from = mid + 1;
        } else {
            return true;
        }
        if from == to {
            return false;
        }
    }
}

fn is_regional_indicator(c: char) -> bool {
    ('\u{1F1E6}'..='\u{1F1FF}').contains(&c)
}

const ZWJ: char = '\u{200D}';

/// The character that starts at byte `pos` of `s`, `pos` being a boundary before the end.
fn char_at(s: &str, pos: usize) -> char {
    match s[pos..].chars().next() {
        Some(c) => c,
        None => unreachable!("char_at is called before the end of the string"),
    }
}

/// The character that ends at byte `pos` of `s`, if any.
fn char_before(s: &str, pos: usize) -> Option<char> {
    s[..pos].chars().next_back()
}

/// Panics, as `str` slicing does (D1), when `pos` lies inside a character of `s`.
pub(crate) fn assert_char_boundary(s: &str, pos: usize) {
    if !s.is_char_boundary(pos) {
        panic!("Position {pos} is inside a character of the string");
    }
}

/// The cluster rule, the one function every caller in the crate reaches it through (`design.md` §4): the port of
/// `findClusterBreak` of `@marijn/find-cluster-break` 1.0.4 (`index.js:41`). `pos` is a `char` boundary of `s`, at
/// most its length.
pub(crate) fn cluster_break(s: &str, pos: usize, forward: bool, include_extending: bool) -> usize {
    if forward { next_cluster_break(s, pos, include_extending) } else { prev_cluster_break(s, pos, include_extending) }
}

/// `nextClusterBreak` (`index.js:45`). cm6 first moves a position between the halves of a surrogate pair to the
/// pair's start (`index.js:48`); a byte position inside a character is a violated precondition here (D1), so every
/// position this sees is a character's start.
fn next_cluster_break(s: &str, pos: usize, include_extending: bool) -> usize {
    if pos == s.len() {
        return pos;
    }
    let mut prev = char_at(s, pos);
    let mut pos = pos + prev.len_utf8();
    while pos < s.len() {
        let next = char_at(s, pos);
        if prev == ZWJ || next == ZWJ || include_extending && is_extending_char(next as u32) {
            pos += next.len_utf8();
            prev = next;
        } else if is_regional_indicator(next) {
            // cm6 counts the indicators before `pos` by stepping back two UTF-16 code units at a time from
            // `pos - 2` (`index.js:57-58`): two units are one indicator, so this counts the run of indicators that
            // ends at `pos`, one character at a time. `prev` is left as it is, as in cm6 (`index.js:60`).
            let (mut count_before, mut i) = (0usize, pos);
            while let Some(c) = char_before(s, i)
                && is_regional_indicator(c)
            {
                count_before += 1;
                i -= c.len_utf8();
            }
            if count_before % 2 == 0 {
                break;
            }
            pos += next.len_utf8();
        } else {
            break;
        }
    }
    pos
}

/// `prevClusterBreak` (`index.js:68`), on characters. cm6 tries the candidates `c = p - 2` for `p = pos, pos - 1,
/// ..., 2` in UTF-16 code units and returns the first forward break from `c` that is below `p`. A candidate inside a
/// surrogate pair starts at the pair (`index.js:48`), so the candidates are the characters that end before the last
/// character before `pos`, walked backward, and the test `found < p` holds exactly when the forward cluster from the
/// candidate's start ends at the candidate's end: `p` is one unit past that end, and a forward break is never before
/// it. The last character before `pos` is never a result: its threshold is `pos` itself, which its forward break
/// reaches. With no candidate (cm6's `pos <= 1`, or no character that passes) the result is 0.
fn prev_cluster_break(s: &str, pos: usize, include_extending: bool) -> usize {
    let Some(last) = char_before(s, pos) else { return 0 };
    let mut end = pos - last.len_utf8();
    while let Some(c) = char_before(s, end) {
        let start = end - c.len_utf8();
        if next_cluster_break(s, start, include_extending) == end {
            return end;
        }
        end = start;
    }
    0
}

/// The next grapheme cluster break after `pos` (forward) or before it (backward), or `pos` itself when the string
/// has no further break in that direction. Moves across extending characters (when `include_extending` is true),
/// characters joined by zero-width joiners, and flag emoji, by the rules of `@marijn/find-cluster-break` 1.0.4.
/// cm6's defaults, which the caller writes (D14): `forward` true, `include_extending` true.
///
/// # Panics
///
/// When `pos` is greater than the length of `s` (`state.cm6.212.d1`) or not on a `char` boundary (D1).
///
/// cm6: findClusterBreak
pub fn find_cluster_break(s: &str, pos: usize, forward: bool, include_extending: bool) -> usize {
    if pos > s.len() {
        // cm6 computes a number from `NaN` here (`state.cm6.212.d1`)
        panic!("Position {pos} is beyond the end of a string of length {}", s.len());
    }
    assert_char_boundary(s, pos);
    cluster_break(s, pos, forward, include_extending)
}

/// The character starting at byte `pos` of `s`; `None` at or beyond the end, where cm6 gives `NaN` (`design.md` §2).
///
/// # Panics
///
/// When `pos` is inside a character (D1).
///
/// cm6: codePointAt
pub fn code_point_at(s: &str, pos: usize) -> Option<char> {
    if pos >= s.len() {
        return None;
    }
    assert_char_boundary(s, pos);
    Some(char_at(s, pos))
}

/// The number of positions a character takes in a string: its UTF-8 length (D1, `design.md` §2).
///
/// cm6: codePointSize
pub fn code_point_size(c: char) -> usize {
    c.len_utf8()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The decoded table against the package's own decoding (`index.js:12-14`), at its ends and its count (332
    /// ranges, `state.findClusterBreak.B5`).
    #[test]
    fn the_table_decodes_as_the_package_decodes_it() {
        assert_eq!(RANGES.0.len(), 332);
        assert_eq!((RANGES.0[0], RANGES.1[0]), (0x300, 0x370));
        assert!(is_extending_char(0x301) && is_extending_char(0x200C) && is_extending_char(0x1F3FB));
        assert!(!is_extending_char(0x2FF) && !is_extending_char(0x200D) && !is_extending_char(0xE0100));
        assert!(RANGES.0.iter().zip(&RANGES.1).all(|(f, t)| f < t));
        assert!(RANGES.1.windows(2).zip(RANGES.0.iter().skip(1)).all(|(w, f)| w[0] <= *f));
    }

    /// The backward rule against cm6's loop run on UTF-16 code units (`index.js:68-75`), over strings mixing
    /// astral characters, marks, ZWJ and regional indicators.
    #[test]
    fn prev_cluster_break_is_cm6s_loop() {
        fn next16(u: &[u16], pos: usize, incl: bool) -> usize {
            let s = String::from_utf16(u).unwrap_or_default();
            let mut pos = pos;
            if pos == u.len() {
                return pos;
            }
            if pos > 0 && (0xDC00..0xE000).contains(&u[pos]) && (0xD800..0xDC00).contains(&u[pos - 1]) {
                pos -= 1;
            }
            let byte = String::from_utf16(&u[..pos]).unwrap_or_default().len();
            let r = next_cluster_break(&s, byte, incl);
            s[..r].encode_utf16().count()
        }
        fn prev16(u: &[u16], mut pos: usize, incl: bool) -> usize {
            while pos > 1 {
                let found = next16(u, pos - 2, incl);
                if found < pos {
                    return found;
                }
                pos -= 1;
            }
            0
        }
        let strings = [
            "",
            "a",
            "ab",
            "a\u{301}b",
            "😀😀a",
            "a😀",
            "🇩🇪🇫🇷🇮🇹x",
            "a\u{200D}b😀\u{200D}😀",
            "\u{301}\u{301}x",
            "é😀\u{1F3FB}z",
        ];
        for s in strings {
            let u: Vec<u16> = s.encode_utf16().collect();
            for (byte, _) in s.char_indices().chain([(s.len(), ' ')]) {
                for incl in [true, false] {
                    let unit = s[..byte].encode_utf16().count();
                    let want = prev16(&u, unit, incl);
                    let got = prev_cluster_break(s, byte, incl);
                    assert_eq!(s[..got].encode_utf16().count(), want, "{s:?} from {byte} ({incl})");
                }
            }
        }
    }
}
