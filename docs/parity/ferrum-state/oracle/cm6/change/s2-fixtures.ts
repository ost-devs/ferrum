const ROOT = "docs/parity/ferrum-state"
const ids: Record<string, string> = {}
for (let line of readFileSync(`${ROOT}/raw/inventory.jsonl`, "utf8").split("\n")) if (line.trim()) {
  let r = JSON.parse(line); if (r.chunk == "change") ids[r.item] = r.id
}
const write = fixtureWriter(`${ROOT}/fixtures/change.jsonl`)
let count = 0
function f(item: string, bs: number[], input: any, extra: string[] = []) {
  if (!ids[item]) throw new Error("unknown item " + item)
  count++
  write(ids[item], bs.map(b => `state.${item}.B${b}`).concat(extra), input, run(input))
}
// Inputs on which cm6 may not terminate run in a child process with a time limit; output {"timeout": ms} when cut off.
function fh(item: string, bs: number[], input: any, extra: string[] = []) {
  count++
  let ms = 5000
  let r = spawnSync("npx", ["tsx", "--tsconfig", ".harness/state/tsconfig.json", `${ROOT}/oracle/cm6/change/interp-cli.ts`, JSON.stringify(input)], {timeout: ms, encoding: "utf8"})
  let output = r.error && (r.error as any).code == "ETIMEDOUT" ? {timeout: ms} : JSON.parse(r.stdout)
  write(ids[item], bs.map(b => `state.${item}.B${b}`).concat(extra), input, output)
}
